-- Votos semanales y mensuales Fan Choice. No modifica ni elimina votos históricos.
BEGIN;
CREATE TABLE IF NOT EXISTS periodic_submissions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  season_id UUID NOT NULL REFERENCES seasons(id) ON DELETE RESTRICT,
  participant_id UUID NOT NULL REFERENCES participants(id) ON DELETE RESTRICT,
  kind TEXT NOT NULL CHECK (kind IN ('weekly_artists','weekly_idols','monthly_artists','monthly_idols')),
  period_key TEXT NOT NULL,
  submitted_date DATE NOT NULL,
  selections JSONB NOT NULL CHECK (jsonb_typeof(selections)='object'),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT periodic_period_format CHECK (
    (kind LIKE 'weekly_%' AND period_key ~ '^\d{4}-\d{2}-\d{2}$') OR
    (kind LIKE 'monthly_%' AND period_key ~ '^\d{4}-\d{2}$')
  ),
  CONSTRAINT periodic_selections_shape CHECK (
    jsonb_typeof(selections->'male')='array' AND jsonb_typeof(selections->'female')='array'
  )
);
CREATE UNIQUE INDEX IF NOT EXISTS periodic_once_per_period
  ON periodic_submissions(season_id,participant_id,kind,period_key);
CREATE INDEX IF NOT EXISTS periodic_season_kind_period
  ON periodic_submissions(season_id,kind,period_key);
ALTER TABLE periodic_submissions ENABLE ROW LEVEL SECURITY;
COMMIT;
